const dictionaries: Record<Locale, Record<Key, string>> = { en, zh };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): T {
  return (key, vars) =>
    dictionaries[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export function defaultLocale(): Locale {
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export const I18n = createContext<{ t: T; locale: Locale }>({ t: translator('en'), locale: 'en' });
export const useI18n = () => useContext(I18n);
